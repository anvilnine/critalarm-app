import 'dart:io';

import 'package:critalarm/core/l10n/shipped_locales.dart';

import 'l10n_parity.dart';

/// Writes the iOS and Android string files from the `native` group of every
/// shipped translation, so the alarm surfaces that run without Flutter speak
/// the language picked in the app. `make l10n` runs it, and
/// `make check-l10n` runs it with `--check`, which fails when a committed
/// file is out of date.
///
/// One source: the English is in `assets/translations/en.json`, under
/// `native`. The outputs are committed, so a native build needs no Dart step:
///
/// - `ios/Shared/L10n/Native.xcstrings`: the `Native` table for the app, the
///   notification extension and the widget extension. Xcode compiles it into
///   one `<lang>.lproj/Native.strings` per language.
/// - `ios/Shared/L10n/NativeText.swift`: one case per key, with its English
///   as the fallback when a bundle has no table.
/// - `ios/Runner/InfoPlist.xcstrings`: the permission prompts.
/// - `ios/Runner/Info.plist`: `CFBundleLocalizations` and the English
///   permission prompts.
/// - `android/.../res/values[-<lang>]/strings.xml`: one file per language.
/// - `android/.../res/xml/locales_config.xml`: the per-app language list.
/// - `android/.../app/critalarm/l10n/NativeText.kt`: one entry per key, with
///   its resource id and its English.
///
/// Placeholders stay as `{name}` in every file. The native code fills them
/// itself, so a translation may move them.
///
/// The pseudo-locale is never written: it is not in [shippedLocaleTags]. iOS
/// fakes it at run time in debug builds and Android builds it in debug with
/// `pseudoLocalesEnabled`.

const nativeGroup = 'native';

/// Keys that are system strings on iOS rather than strings the code looks
/// up: they go to `InfoPlist.xcstrings` under these Info.plist keys, and to
/// no other file.
const infoPlistKeys = {
  'native.permission.microphone': 'NSMicrophoneUsageDescription',
  'native.permission.alarmkit': 'NSAlarmKitUsageDescription',
};

const iosTablePath = 'ios/Shared/L10n/Native.xcstrings';
const iosSwiftPath = 'ios/Shared/L10n/NativeText.swift';
const iosInfoStringsPath = 'ios/Runner/InfoPlist.xcstrings';
const iosInfoPlistPath = 'ios/Runner/Info.plist';
const androidResPath = 'android/app/src/main/res';
const androidKotlinPath =
    'android/app/src/main/kotlin/app/critalarm/l10n/NativeText.kt';

const _header =
    'Generated by tool/l10n_native.dart from assets/translations. '
    'Do not edit; run make l10n.';

/// Every string under `native`, keyed by its dotted path.
Map<String, String> nativeStrings(Map<String, dynamic> translation) {
  final group = translation[nativeGroup];
  if (group is! Map<String, dynamic>) {
    throw const FormatException('no "native" group');
  }
  final out = <String, String>{};
  void walk(Map<String, dynamic> map, String path) {
    for (final entry in map.entries) {
      final key = '$path.${entry.key}';
      final value = entry.value;
      if (value is Map<String, dynamic>) {
        walk(value, key);
      } else if (value is String) {
        out[key] = value;
      } else {
        throw FormatException('$key: expected a string');
      }
    }
  }

  walk(group, nativeGroup);
  return out;
}

/// `native.widget.open_count` without its group, as parts:
/// `[widget, open, count]`.
List<String> _words(String key) =>
    key.substring(nativeGroup.length + 1).split(RegExp('[._]'));

String swiftCase(String key) {
  final words = _words(key);
  return words.first +
      words.skip(1).map((w) => w[0].toUpperCase() + w.substring(1)).join();
}

String kotlinEntry(String key) => _words(key).join('_').toUpperCase();

String androidName(String key) => key.replaceAll('.', '_');

/// The `values-` folder suffix for a tag: `pt-BR` is `pt-rBR`, a tag with a
/// script uses the `b+` form (`zh-Hans` is `b+zh+Hans`).
String androidQualifier(String tag) {
  final parts = tag.split('-');
  if (parts.length == 1) return parts.first;
  if (parts.any((part) => part.length == 4)) return 'b+${parts.join('+')}';
  return '${parts.first}-r${parts[1]}';
}

String _swiftString(String value) {
  final escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll('"', r'\"')
      .replaceAll('\n', r'\n');
  return '"$escaped"';
}

String _kotlinString(String value) {
  final escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll('"', r'\"')
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n');
  return '"$escaped"';
}

String androidValue(String value) {
  var escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll('&', '&amp;')
      .replaceAll('<', '&lt;')
      .replaceAll('>', '&gt;')
      .replaceAll("'", r"\'")
      .replaceAll('"', r'\"')
      .replaceAll('\n', r'\n');
  if (escaped.startsWith('@') || escaped.startsWith('?')) {
    escaped = '\\$escaped';
  }
  return escaped;
}

String _xmlText(String value) => value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;');

/// A string catalog in the layout Xcode itself writes (sorted keys, two
/// space indent, ` : `), so opening it in Xcode changes nothing. Every key is
/// `manual`, so Xcode never marks one stale or adds its own.
String xcstrings(Map<String, Map<String, String>> byLocale) {
  final keys = byLocale.values.expand((m) => m.keys).toSet().toList()..sort();
  final locales = byLocale.keys.toList()..sort();
  final buffer = StringBuffer()
    ..writeln('{')
    ..writeln('  "sourceLanguage" : "en",')
    ..writeln('  "strings" : {');
  for (var k = 0; k < keys.length; k++) {
    final key = keys[k];
    buffer
      ..writeln('    ${jsonEncode(key)} : {')
      ..writeln('      "extractionState" : "manual",')
      ..writeln('      "localizations" : {');
    final present = [
      for (final locale in locales)
        if (byLocale[locale]!.containsKey(key)) locale,
    ];
    for (var l = 0; l < present.length; l++) {
      final locale = present[l];
      buffer
        ..writeln('        ${jsonEncode(locale)} : {')
        ..writeln('          "stringUnit" : {')
        ..writeln('            "state" : "translated",')
        ..writeln(
          '            "value" : ${jsonEncode(byLocale[locale]![key])}',
        )
        ..writeln('          }')
        ..writeln('        }${l == present.length - 1 ? '' : ','}');
    }
    buffer
      ..writeln('      }')
      ..writeln('    }${k == keys.length - 1 ? '' : ','}');
  }
  buffer
    ..writeln('  },')
    ..writeln('  "version" : "1.0"')
    ..writeln('}');
  return buffer.toString();
}

String swiftNativeText(Map<String, String> english, List<String> keepWords) {
  final keys = english.keys.toList()..sort();
  final buffer = StringBuffer()
    ..writeln('// $_header')
    ..writeln()
    ..writeln('/// One case per string in the `native` group of `en.json`. The')
    ..writeln('/// raw value is the key in the `Native` table.')
    ..writeln('enum NativeText: String, CaseIterable {');
  for (final key in keys) {
    buffer.writeln('    case ${swiftCase(key)} = ${_swiftString(key)}');
  }
  buffer
    ..writeln()
    ..writeln('    /// The English, used when a bundle has no `Native` table.')
    ..writeln('    var english: String {')
    ..writeln('        switch self {');
  for (final key in keys) {
    buffer.writeln(
      '        case .${swiftCase(key)}: return ${_swiftString(english[key]!)}',
    );
  }
  buffer
    ..writeln('        }')
    ..writeln('    }')
    ..writeln('}')
    ..writeln()
    ..writeln('extension NativeL10n {')
    ..writeln('    /// `tool/l10n_keep.txt`: words the pseudo-locale leaves as')
    ..writeln('    /// they are.')
    ..writeln(
      '    static let keepWords: [String] = '
      '[${keepWords.map(_swiftString).join(', ')}]',
    )
    ..writeln('}');
  return buffer.toString();
}

String kotlinNativeText(Map<String, String> english) {
  final keys = english.keys.toList()..sort();
  final buffer = StringBuffer()
    ..writeln('// $_header')
    ..writeln()
    ..writeln('package app.critalarm.l10n')
    ..writeln()
    ..writeln('import app.critalarm.R')
    ..writeln()
    ..writeln('/**')
    ..writeln(' * One entry per string in the `native` group of `en.json`: its')
    ..writeln(' * resource and its English, which the JVM tests and a failed')
    ..writeln(' * resource lookup use.')
    ..writeln(' */')
    ..writeln('enum class NativeText(val resId: Int, val english: String) {');
  for (var i = 0; i < keys.length; i++) {
    final key = keys[i];
    final end = i == keys.length - 1 ? ';' : ',';
    buffer.writeln(
      '    ${kotlinEntry(key)}(R.string.${androidName(key)}, '
      '${_kotlinString(english[key]!)})$end',
    );
  }
  buffer.writeln('}');
  return buffer.toString();
}

String androidStrings(Map<String, String> strings) {
  final keys = strings.keys.toList()..sort();
  final buffer = StringBuffer()
    ..writeln('<?xml version="1.0" encoding="utf-8"?>')
    ..writeln('<!-- $_header -->')
    ..writeln('<resources>');
  for (final key in keys) {
    buffer.writeln(
      '    <string name="${androidName(key)}">'
      '${androidValue(strings[key]!)}</string>',
    );
  }
  buffer.writeln('</resources>');
  return buffer.toString();
}

String localesConfig(List<String> tags) {
  final buffer = StringBuffer()
    ..writeln('<?xml version="1.0" encoding="utf-8"?>')
    ..writeln('<!-- $_header -->')
    ..writeln(
      '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">',
    );
  for (final tag in tags) {
    buffer.writeln('    <locale android:name="$tag" />');
  }
  buffer.writeln('</locale-config>');
  return buffer.toString();
}

/// [plist] with `CFBundleLocalizations` set to [tags] and each permission
/// prompt set to its English. A key that is missing is added before the
/// closing `</dict>`.
String updateInfoPlist(
  String plist, {
  required List<String> tags,
  required Map<String, String> prompts,
}) {
  var out = plist;
  void setEntry(String key, String valueXml) {
    final pattern = RegExp(
      '(\t*)<key>${RegExp.escape(key)}</key>\\s*'
      r'(<string>[^<]*</string>|<array>[\s\S]*?</array>|<array/>)',
    );
    final match = pattern.firstMatch(out);
    if (match != null) {
      final indent = match.group(1)!;
      out = out.replaceRange(
        match.start,
        match.end,
        '$indent<key>$key</key>\n$indent${valueXml.replaceAll('\n', '\n$indent')}',
      );
    } else {
      final end = out.lastIndexOf('</dict>');
      out = out.replaceRange(
        end,
        end,
        '\t<key>$key</key>\n\t${valueXml.replaceAll('\n', '\n\t')}\n',
      );
    }
  }

  setEntry(
    'CFBundleLocalizations',
    '<array>\n${tags.map((t) => '\t<string>$t</string>').join('\n')}\n</array>',
  );
  for (final entry in prompts.entries) {
    setEntry(entry.key, '<string>${_xmlText(entry.value)}</string>');
  }
  return out;
}

/// Every file this tool owns, path to contents, from [root].
Map<String, String> generate(Directory root) {
  final translations = '${root.path}/assets/translations';
  final keepWords = readKeepWords(File('${root.path}/tool/l10n_keep.txt'));
  if (!shippedLocaleTags.contains('en')) {
    throw const FormatException('shippedLocaleTags must list en');
  }
  final byLocale = <String, Map<String, String>>{};
  for (final tag in shippedLocaleTags) {
    final file = File('$translations/$tag.json');
    if (!file.existsSync()) {
      throw FormatException('$tag is shipped but ${file.path} is missing');
    }
    byLocale[tag] = nativeStrings(readTranslation(file));
  }

  final english = byLocale['en']!;
  Map<String, String> code(Map<String, String> strings) => {
    for (final entry in strings.entries)
      if (!infoPlistKeys.containsKey(entry.key)) entry.key: entry.value,
  };
  Map<String, String> prompts(Map<String, String> strings) => {
    for (final entry in infoPlistKeys.entries)
      if (strings.containsKey(entry.key)) entry.value: strings[entry.key]!,
  };
  for (final key in infoPlistKeys.keys) {
    if (!english.containsKey(key)) {
      throw FormatException('en.json has no $key');
    }
  }

  final out = <String, String>{
    iosTablePath: xcstrings({
      for (final entry in byLocale.entries) entry.key: code(entry.value),
    }),
    iosSwiftPath: swiftNativeText(code(english), keepWords),
    iosInfoStringsPath: xcstrings({
      for (final entry in byLocale.entries) entry.key: prompts(entry.value),
    }),
    iosInfoPlistPath: updateInfoPlist(
      File('${root.path}/$iosInfoPlistPath').readAsStringSync(),
      tags: shippedLocaleTags,
      prompts: prompts(english),
    ),
    '$androidResPath/xml/locales_config.xml': localesConfig(shippedLocaleTags),
    androidKotlinPath: kotlinNativeText(code(english)),
  };
  for (final entry in byLocale.entries) {
    final folder = entry.key == 'en'
        ? 'values'
        : 'values-${androidQualifier(entry.key)}';
    out['$androidResPath/$folder/strings.xml'] = androidStrings(
      code(entry.value),
    );
  }
  return out;
}

/// `fvm dart run tool/l10n_native.dart` writes the files.
/// `--check` writes nothing and fails when any file differs.
void main(List<String> arguments) {
  final check = arguments.contains('--check');
  final unknown = arguments.where((a) => a != '--check').toList();
  if (unknown.isNotEmpty) {
    stderr.writeln('Usage: l10n_native.dart [--check]');
    exitCode = 64;
    return;
  }
  try {
    final files = generate(Directory.current);
    final stale = <String>[];
    for (final entry in files.entries) {
      final file = File(entry.key);
      final current = file.existsSync() ? file.readAsStringSync() : null;
      if (current == entry.value) continue;
      if (check) {
        stale.add(entry.key);
      } else {
        file
          ..createSync(recursive: true)
          ..writeAsStringSync(entry.value);
        stdout.writeln('Wrote ${entry.key}');
      }
    }
    if (check && stale.isNotEmpty) {
      stderr
        ..writeln(stale.join('\n'))
        ..writeln('Native strings are out of date. Run make l10n.');
      exitCode = 1;
    } else if (check) {
      stdout.writeln('Native strings are up to date.');
    }
  } on Object catch (error) {
    stderr.writeln('Native string generation FAILED: $error');
    exitCode = 1;
  }
}
